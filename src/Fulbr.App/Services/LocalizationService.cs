    private string _language = "System";

    public string Language
    {
        get => _language;
        set
        {
            _language = value;
            EffectiveLanguage = value.Equals("Russian", StringComparison.OrdinalIgnoreCase)
                ? "Russian"
                : value.Equals("English", StringComparison.OrdinalIgnoreCase)
                    ? "English"
                    : (CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "ru" ? "Russian" : "English");
        }
    }

    public string EffectiveLanguage { get; private set; } = "English";

    public string this[string key]
    {
        get
        {
            var dictionary = EffectiveLanguage == "Russian" ? Russian : English;
            return dictionary.TryGetValue(key, out var value) ? value : key;
        }
    }
